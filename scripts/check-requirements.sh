#!/usr/bin/env bash
# 회장 확정 요구사항 반영 검사 (회장 2026-08-18 "왜 요청을 한 턴만 지나면 개무시하는지 분석")
# 대장: docs/requests/회장-확정-요구사항-대장.md
# 사용: bash scripts/check-requirements.sh <프로토타입.html>
set -uo pipefail
F="${1:-}"
[ -f "$F" ] || { echo "사용: $0 <프로토타입.html>" >&2; exit 2; }

# "번호|요구 요약|검사어1;검사어2"  (검사어 중 하나라도 있으면 통과)
REQS=(
"R02|학습 정보 상시 열람·수정|학습 정보"
"R03|학습 입력 경로 넷|노션;위키"
"R08|사이드바 네 방|Studio 생성;발행실;성과실"
"R09|작업물 목록 상단|내 작업물"
"R11|운영 취향(발행 쪽 학습)|운영 취향"
"R12|공통 정보 상위 층위|공통 정보"
"R13|되돌리기는 항목 추가|되돌리"
"R15|학습 정보 헤더 노출|학습 정보"
"R16|단계별 보관과 이어서 작업|이어서 작업;보관"
"R17|발행 선택지 세 문구|지금 발행하기;승인 인박스에 보관하기;캘린더로 예약하기"
"R19|좌측 흐름 색인|흐름 색인;sidenav"
"R20|우측 해설 세 항목|심리 근거;벤치마크;실구현"
"R23|방 이름 후보 비교|방 이름"
)
echo "회장 확정 요구사항 검사: $F"
echo "------------------------------------------------------------"
fail=0
for row in "${REQS[@]}"; do
  IFS='|' read -r id name keys <<< "$row"
  ok=0
  IFS=';' read -r -a arr <<< "$keys"
  for k in "${arr[@]}"; do
    if grep -qF "$k" "$F" 2>/dev/null; then ok=1; break; fi
  done
  if [ "$ok" -eq 0 ]; then
    printf "  누락  %-5s %s\n" "$id" "$name"
    fail=$((fail + 1))
  fi
done
echo "------------------------------------------------------------"
if [ "$fail" -gt 0 ]; then
  echo "판정: 반려. 회장이 확정한 요구 ${fail}건이 화면에 없다."
  echo "  대장 전체를 위임서에 첨부하고 다시 만들어라. 발췌하지 마라."
  exit 1
fi
echo "판정: 통과. 대장의 요구가 전부 화면에 있다."
exit 0
