#!/usr/bin/env bash
# 제품 화면 순수성 검사 (회장 2026-08-18 "화면에다가 뭐가 추가됐는지 제안인지 이런거 쓰지말라고 하지 않았냐")
#
# 사고: v36 성과실·발행실 기기 프레임 안에 프로토타입 설명물이 들어갔다.
#   "이 방의 소유 openclaw-service · 순서 4/4 · 이름 후보 공간형(회장 구상 원안)"
#   "상단 매트릭스의 방 이름에서 네 벌을 갈아 끼워 비교하실 수 있습니다. 고르는 것은 회장님입니다."
#   "근거 표시 세 가지" 범례 상자
# 이것들은 회장에게 하는 말이지 제품 사용자에게 하는 말이 아니다. 제품 화면에 있으면 쓰레기장이 된다.
#
# 원칙: 기기 프레임 안 = 제품. 프레임 밖(좌 색인·우 해설·상단 매트릭스) = 프로토타입 설명.
#       이 경계를 넘는 문구는 전부 결함이다.
#
# 기존 check-prototype-changelog.sh는 "변경점 패널이 있는가"만 봤고
# 프레임 안에 회장용 메타가 새어 들어간 것은 보지 않았다. 그 구멍을 메운다.
#
# 사용: bash scripts/check-frame-purity.sh <프로토타입.html>
# 종료: 0=PASS, 1=FAIL

set -uo pipefail
F="${1:-}"
[ -z "$F" ] && { echo "사용: $0 <프로토타입.html>" >&2; exit 2; }
[ -f "$F" ] || { echo "파일 없음: $F" >&2; exit 2; }

# 제품 화면에 있으면 안 되는 문구. 회장을 향한 말 또는 프로토타입 자기언급.
BANNED=(
  "회장"
  "이번에 더함"
  "이번 판"
  "에서 바뀐"
  "상단 매트릭스"
  "갈아 끼워"
  "이 방의 소유"
  "이름 후보"
  "권장 뷰포트"
  "실구현 경로"
  "심리 근거"
  "벤치마크"
  "프로토타입"
  "시안"
  "제안입니다"
  "미구현"
  "추후 구현"
)

echo "제품 화면 순수성 검사: $F"
echo "----------------------------------------"

# 화면 렌더 함수 영역만 본다. 좌측 색인·우측 해설·상단 매트릭스 렌더는 제외 대상이지만
# 파일 구조상 완전 분리가 어려우므로, 금지어가 몇 건 있는지 세고 위치를 찍어 사람이 판정하게 한다.
hits=0
for w in "${BANNED[@]}"; do
  # sidecard / sidenav / matrix / stamp 영역 밖에서 나온 것만 후보로 본다
  lines=$(grep -n "$w" "$F" 2>/dev/null \
    | grep -viE "sidecard|sidenav|matrix|stamp|hub-|mx-|sc-|li-t|flowindex|해설|색인" || true)
  n=$(printf '%s' "$lines" | grep -c . || true)
  if [ "${n:-0}" -gt 0 ]; then
    echo "  의심: \"$w\" ${n}건"
    printf '%s\n' "$lines" | head -2 | sed 's/^/      /' | cut -c1-140
    hits=$((hits + n))
  fi
done

echo "----------------------------------------"
if [ "$hits" -gt 0 ]; then
  cat <<'EOF'
판정: 반려 후보. 위 문구가 기기 프레임 안(제품 화면)에 있으면 결함이다.

경계 규칙:
  프레임 안  = 제품. 실제 사용자가 볼 것만. 라벨과 값과 버튼.
  프레임 밖  = 프로토타입 설명. 실구현 경로·심리 근거·벤치마크·이번 판 변경점은 전부 여기.

각 건이 프레임 안인지 밖인지 직접 확인하고, 프레임 안이면 밖으로 옮겨라.
옮길 자리가 없다는 이유로 프레임 안에 두지 마라. 그것이 화면을 쓰레기장으로 만든 원인이다.
EOF
  exit 1
fi
echo "판정: 통과. 제품 화면에 프로토타입 설명물이 없다."
exit 0
